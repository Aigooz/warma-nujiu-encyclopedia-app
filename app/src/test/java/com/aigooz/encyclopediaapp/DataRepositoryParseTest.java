package com.aigooz.encyclopediaapp;

import org.junit.Test;
import static org.junit.Assert.*;

/**
 * 覆盖 DataRepository 中数据/题库的文本裁剪逻辑。
 *
 * 这两段逻辑原先用「第一个等号」和「最后一个右方括号」定位，属于格式强耦合：
 * 文件头注释里出现等号、或数组之后追加含 ']' 的内容，都会导致解析错位。
 * 这里明确锁定修正后的行为。
 */
public class DataRepositoryParseTest {

    @Test public void stripDataHandlesPlainAssignment() {
        assertEquals("{\"a\":1}", DataRepository.stripData("const RAW = {\"a\":1};"));
        assertEquals("{\"a\":1}", DataRepository.stripData("RAW={\"a\":1}"));
    }

    /** 关键回归：文件头注释中含等号时必须仍能正确定位赋值语句。 */
    @Test public void stripDataIgnoresEqualsInsideLeadingComments() {
        String text = "// Warma 百科 · 数据（自动生成）\n// version=v18\nconst RAW = {\"a\":1};";
        assertEquals("{\"a\":1}", DataRepository.stripData(text));
    }

    @Test public void stripDataIgnoresEqualsInsideJsonValues() {
        String text = "const RAW = {\"url\":\"a=b\",\"x\":1};";
        assertEquals("{\"url\":\"a=b\",\"x\":1}", DataRepository.stripData(text));
    }

    @Test public void stripQuizExtractsFirstArray() {
        String text = "// generated by generate_quiz.js\nconst QUIZ_DATA = [{\"id\":1}];";
        assertEquals("[{\"id\":1}]", DataRepository.stripQuiz(text));
    }

    /** 关键回归：数组之后若再出现 ']'（旧实现用 lastIndexOf 会取错），仍应取第一个完整数组。 */
    @Test public void stripQuizIgnoresBracketsAfterTheArray() {
        String text = "const QUIZ_DATA = [{\"id\":1},{\"id\":2}];\n// footer ] ignore me";
        assertEquals("[{\"id\":1},{\"id\":2}]", DataRepository.stripQuiz(text));
    }

    @Test public void stripQuizIgnoresBracketsInsideStrings() {
        String text = "const QUIZ_DATA = [{\"q\":\"选项 [A] 或 [B]\"}];";
        assertEquals("[{\"q\":\"选项 [A] 或 [B]\"}]", DataRepository.stripQuiz(text));
    }

    @Test public void stripQuizHandlesEscapedQuotes() {
        String text = "const QUIZ_DATA = [{\"q\":\"say \\\"]\\\" now\"}];";
        assertEquals("[{\"q\":\"say \\\"]\\\" now\"}]", DataRepository.stripQuiz(text));
    }

    @Test public void matchArrayEndReportsUnclosedArray() {
        assertEquals(-1, DataRepository.matchArrayEnd("[\"a\", \"b\"", 0));
        assertEquals(4, DataRepository.matchArrayEnd("[\"a\"]", 0));
    }

    @Test public void stripQuizRejectsMissingArray() {
        try {
            DataRepository.stripQuiz("const QUIZ_DATA = nothing;");
            fail("Expected failure when the quiz array is missing");
        } catch (RuntimeException expected) {
            // 期望：明确报错，而不是抛出难以定位的 StringIndexOutOfBoundsException
        }
    }
}
